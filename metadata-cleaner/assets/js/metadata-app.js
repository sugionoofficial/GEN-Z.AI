async function toBlobURL(
    url,
    mimeType
) {

    const response =
        await fetch(
            url
        );


    if (
        !response.ok
    ) {

        throw new Error(
            `Gagal mengambil FFmpeg resource: ${response.status}`
        );
    }


    const blob =
        await response.blob();


    return URL.createObjectURL(
        new Blob(
            [
                blob
            ],
            {
                type:
                    mimeType
            }
        )
    );
}


/* =========================================================
   FFMPEG WAIT
========================================================= */

function waitForFFmpeg() {

    return new Promise(
        (resolve, reject) => {

            const start =
                Date.now();


            const timer =
                setInterval(
                    () => {

                        if (
                            state.ffmpegLoaded &&
                            state.ffmpeg
                        ) {

                            clearInterval(
                                timer
                            );

                            resolve(
                                state.ffmpeg
                            );

                            return;
                        }


                        if (
                            Date.now() -
                            start >
                            120000
                        ) {

                            clearInterval(
                                timer
                            );

                            reject(
                                new Error(
                                    "FFmpeg membutuhkan waktu terlalu lama untuk dimuat."
                                )
                            );
                        }

                    },
                    100
                );
        }
    );
}


