function handleFileInput(event) {

    const files =
        Array.from(
            event.target?.files || []
        );

    if (!files.length) {

        return;
    }

    processSelectedFile(
        files[0]
    );
}


function handleDragOver(event) {

    event.preventDefault();

    elements.dropzone?.classList.add(
        "is-dragging"
    );
}


function handleDragLeave(event) {

    event.preventDefault();

    elements.dropzone?.classList.remove(
        "is-dragging"
    );
}


function handleDrop(event) {

    event.preventDefault();

    elements.dropzone?.classList.remove(
        "is-dragging"
    );

    const files =
        Array.from(
            event.dataTransfer?.files || []
        );

    if (!files.length) {

        return;
    }

    processSelectedFile(
        files[0]
    );
}


/* =========================================================
   FILE PROCESSING
========================================================= */

function processSelectedFile(file) {

    if (!file) {

        return;
    }


    if (
        !isSupportedMedia(file)
    ) {

        setStatus(
            "UNKNOWN",
            "FORMAT TIDAK DIDUKUNG",
            "Pilih file foto atau video yang dapat diproses oleh browser."
        );

        return;
    }


    resetForNewFile();


    state.file = file;

    state.fileType =
        detectMediaType(file);


    state.originalURL =
        URL.createObjectURL(file);


    updateFileInfo();

    renderOriginalPreview();

    elements.checkButton.disabled = false;

    elements.cleanButton.disabled = true;

    elements.downloadButton.disabled = true;

    setPreviewStatus(
        "MEDIA SIAP. TEKAN CHECK UNTUK MEMBACA METADATA."
    );

    setStatus(
        "UNKNOWN",
        "BELUM DIPERIKSA",
        "Tekan CHECK untuk membaca metadata media."
    );
}


/* =========================================================
   TYPE DETECTION
========================================================= */

function isSupportedMedia(file) {

    if (!file) {

        return false;
    }


    if (
        file.type &&
        (
            file.type.startsWith("image/") ||
            file.type.startsWith("video/")
        )
    ) {

        return true;
    }


    const extension =
        getExtension(
            file.name
        );


    return [
        "jpg",
        "jpeg",
        "png",
        "webp",
        "gif",
        "bmp",
        "tif",
        "tiff",
        "avif",
        "mp4",
        "mov",
        "m4v",
        "webm",
        "mkv",
        "avi",
        "mpeg",
        "mpg",
        "3gp",
        "ogv"
    ].includes(
        extension
    );
}


function detectMediaType(file) {

    if (
        file.type?.startsWith(
            "image/"
        )
    ) {

        return "image";
    }


    if (
        file.type?.startsWith(
            "video/"
        )
    ) {

        return "video";
    }


    const extension =
        getExtension(
            file.name
        );


    if (
        [
            "jpg",
            "jpeg",
            "png",
            "webp",
            "gif",
            "bmp",
            "tif",
            "tiff",
            "avif"
        ].includes(
            extension
        )
    ) {

        return "image";
    }


    return "video";
}


