/* =========================================================
   AI DETECTION
   ---------------------------------------------------------
   Metadata-only detection.

   Aturan:
   - Tidak menggunakan "ai" sebagai keyword tunggal.
   - Matching menggunakan batas kata.
   - Identifier AI yang jelas tetap terdeteksi.
   - Nama umum seperti "runway", "pika", "gemini", dll.
     tidak dianggap indikator hanya karena muncul sebagai
     kata biasa.
   - Hasil detection adalah indikator metadata,
     bukan bukti media benar-benar dibuat oleh AI.
========================================================= */

export function detectAIIndicators(
    metadata
) {

    const matches = [];

    const seen =
        new Set();


    /* =====================================================
       STRONG IDENTIFIERS
    ===================================================== */

    const strongPatterns = [

        /\bartificial intelligence\b/i,

        /\bgenerative ai\b/i,

        /\bgenerated by ai\b/i,

        /\bai generated\b/i,

        /\bai-generated\b/i,

        /\bai generated content\b/i,

        /\bai-generated content\b/i,

        /\bsynthetic media\b/i,

        /\bsynthetic image\b/i,

        /\bsynthetic video\b/i,

        /\bsynthetic content\b/i,

        /\bmidjourney\b/i,

        /\bstable diffusion\b/i,

        /\bcomfyui\b/i,

        /\bautomatic1111\b/i,

        /\bautomatic 1111\b/i,

        /\bfooocus\b/i,

        /\bleonardo ai\b/i,

        /\badobe firefly\b/i,

        /\bdall-e\b/i,

        /\bdalle\b/i,

        /\bopenai\b/i,

        /\bsora\b/i,

        /\brunwayml\b/i,

        /\brunway ai\b/i,

        /\bpika labs\b/i,

        /\bpika ai\b/i,

        /\bkling ai\b/i,

        /\bhailuo ai\b/i,

        /\bminimax ai\b/i,

        /\bluma ai\b/i,

        /\bdreamina\b/i,

        /\bseedance\b/i,

        /\bseedream\b/i,

        /\bblack forest labs\b/i,

        /\bideogram\b/i,

        /\bcanva ai\b/i,

        /\bgemini ai\b/i,

        /\bimagen\b/i,

        /\bnovelai\b/i,

        /\bpixverse\b/i,

        /\bveo\b/i,

        /\bsynthesia\b/i,

        /\bheygen\b/i,

        /\binvideo ai\b/i,

        /\bcapcut ai\b/i,

        /\btopaz ai\b/i,

        /\bgenerative fill\b/i,

        /\bgenerative expand\b/i,

        /\btext[- ]to[- ]image\b/i,

        /\btext[- ]to[- ]video\b/i,

        /\bimage generation\b/i,

        /\bimage generated\b/i,

        /\bvideo generation\b/i,

        /\bvideo generated\b/i

    ];


    /* =====================================================
       CONTEXTUAL IDENTIFIERS
    ===================================================== */

    const contextualPatterns = [

        {
            name:
                "firefly",

            pattern:
                /\bfirefly\b/i
        },

        {
            name:
                "runway",

            pattern:
                /\brunway\b/i
        },

        {
            name:
                "pika",

            pattern:
                /\bpika\b/i
        },

        {
            name:
                "kling",

            pattern:
                /\bkling\b/i
        },

        {
            name:
                "hailuo",

            pattern:
                /\bhailuo\b/i
        },

        {
            name:
                "minimax",

            pattern:
                /\bminimax\b/i
        },

        {
            name:
                "luma",

            pattern:
                /\bluma\b/i
        },

        {
            name:
                "gemini",

            pattern:
                /\bgemini\b/i
        },

        {
            name:
                "veo",

            pattern:
                /\bveo\b/i
        }

    ];


    for (
        const item of metadata || []
    ) {

        if (
            !item
        ) {

            continue;
        }


        const field =
            String(
                item.field || ""
            );


        const value =
            String(
                item.value || ""
            );


        const source =
            String(
                item.source || ""
            );


        const combined =
            `${field} ${value} ${source}`;


        /* =================================================
           STRONG MATCH
        ================================================= */

        for (
            const pattern of strongPatterns
        ) {

            const match =
                combined.match(
                    pattern
                );


            if (
                !match
            ) {

                continue;
            }


            const keyword =
                match[0]
                    .trim()
                    .toLowerCase();


            const key =
                `strong::${keyword}::${field}::${value}`;


            if (
                seen.has(key)
            ) {

                continue;
            }


            seen.add(
                key
            );


            matches.push({

                keyword,

                field,

                value,

                source

            });
        }


        /* =================================================
           CONTEXTUAL MATCH
        ================================================= */

        const contextualField =
            (
                /software/i.test(field) ||
                /encoder/i.test(field) ||
                /creator/i.test(field) ||
                /author/i.test(field) ||
                /application/i.test(field) ||
                /producer/i.test(field) ||
                /handler/i.test(field) ||
                /writing/i.test(field) ||
                /generator/i.test(field) ||
                /model/i.test(field) ||
                /tool/i.test(field) ||
                /comment/i.test(field) ||
                /description/i.test(field) ||
                /title/i.test(field) ||
                /vendor/i.test(field)
            );


        if (
            !contextualField
        ) {

            continue;
        }


        for (
            const itemPattern of contextualPatterns
        ) {

            if (
                !itemPattern.pattern.test(
                    value
                )
            ) {

                continue;
            }


            const keyword =
                itemPattern.name;


            const key =
                `context::${keyword}::${field}::${value}`;


            if (
                seen.has(key)
            ) {

                continue;
            }


            seen.add(
                key
            );


            matches.push({

                keyword,

                field,

                value,

                source

            });
        }
    }


    return matches;
}
